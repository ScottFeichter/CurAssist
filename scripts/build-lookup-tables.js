/**
 * build-lookup-tables.js
 *
 * Fetches categories and eligibilities from the SF Service Guide API
 * and generates lookup table files for both server-side (TypeScript)
 * and browser-side (JavaScript) use.
 *
 * Run: node scripts/build-lookup-tables.js
 * Called as part of the build pipeline.
 */

const fs = require('fs');
const path = require('path');

const CATEGORIES_URL = 'https://www.sfserviceguide.org/api/v2/categories';
const ELIGIBILITIES_URL = 'https://www.sfserviceguide.org/api/v2/eligibilities';

const SERVER_OUTPUT = path.resolve(__dirname, '../src/server/helpers/lookup-tables/generated-lookups.ts');
const BROWSER_OUTPUT = path.resolve(__dirname, '../src/public/frontend/Scripts/data/lookup-tables.js');

async function fetchJSON(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Failed to fetch ${url}: ${res.status}`);
  return res.json();
}

async function main() {
  console.log('[build-lookup-tables] Fetching categories...');
  const catData = await fetchJSON(CATEGORIES_URL);
  const categories = catData.categories || [];

  console.log('[build-lookup-tables] Fetching eligibilities...');
  const eligData = await fetchJSON(ELIGIBILITIES_URL);
  const eligibilities = eligData.eligibilities || [];

  console.log(`[build-lookup-tables] Got ${categories.length} categories, ${eligibilities.length} eligibilities`);

  // Build name → id maps
  const categoryMap = {};
  for (const c of categories) {
    categoryMap[c.name] = c.id;
  }

  const eligibilityMap = {};
  for (const e of eligibilities) {
    eligibilityMap[e.name] = e.id;
  }

  // Build valid name Sets (for fast validation)
  const categoryNames = categories.map(c => c.name).sort();
  const eligibilityNames = eligibilities.map(e => e.name).sort();

  // Generate server-side TypeScript
  const serverContent = `/**
 * AUTO-GENERATED by scripts/build-lookup-tables.js — DO NOT EDIT
 * Source: ${CATEGORIES_URL} and ${ELIGIBILITIES_URL}
 * Generated: ${new Date().toISOString()}
 */

/** Valid SFSG category names for validation */
export const validCategoryNames: ReadonlySet<string> = new Set(${JSON.stringify(categoryNames, null, 2)});

/** Valid SFSG eligibility names for validation */
export const validEligibilityNames: ReadonlySet<string> = new Set(${JSON.stringify(eligibilityNames, null, 2)});

/** Category name → SFSG ID */
export const categoryLookup: Readonly<Record<string, number>> = ${JSON.stringify(categoryMap, null, 2)};

/** Eligibility name → SFSG ID */
export const eligibilityLookup: Readonly<Record<string, number>> = ${JSON.stringify(eligibilityMap, null, 2)};
`;

  // Generate browser-side JavaScript
  const browserContent = `// AUTO-GENERATED by scripts/build-lookup-tables.js — DO NOT EDIT
// Source: ${CATEGORIES_URL} and ${ELIGIBILITIES_URL}
// Generated: ${new Date().toISOString()}

/** Valid SFSG category names for validation */
const validCategoryNames = new Set(${JSON.stringify(categoryNames, null, 2)});

/** Valid SFSG eligibility names for validation */
const validEligibilityNames = new Set(${JSON.stringify(eligibilityNames, null, 2)});

/** Category name → SFSG ID */
const categoryLookup = ${JSON.stringify(categoryMap, null, 2)};

/** Eligibility name → SFSG ID */
const eligibilityLookup = ${JSON.stringify(eligibilityMap, null, 2)};
`;

  fs.writeFileSync(SERVER_OUTPUT, serverContent);
  console.log(`[build-lookup-tables] Wrote ${SERVER_OUTPUT}`);

  fs.writeFileSync(BROWSER_OUTPUT, browserContent);
  console.log(`[build-lookup-tables] Wrote ${BROWSER_OUTPUT}`);

  console.log('[build-lookup-tables] Done.');
}

main().catch(err => {
  console.error('[build-lookup-tables] FATAL:', err.message);
  process.exit(1);
});
